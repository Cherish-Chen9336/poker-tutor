import { lazy, Suspense, useEffect, useRef, useState } from "react";
import { parseLocation, routeHref, useHash, type Route } from "./app/route";
import { I18nProvider, LanguageErrorBoundary, LanguageSwitch, LoadingLanguage, MachineLabel } from "./i18n/I18n";
import { useHref, useLocale, useT } from "./i18n/hooks";
import type { Locale } from "./i18n/locales";
import type { MessageId } from "./i18n/messages/en";
import { focusPageHeading } from "./app/focus";
import { useProgress } from "./app/progress";
import { LearnHome } from "./learn/LearnHome";
import { findLesson } from "./learn/lessons";

// Lesson pages include the hand evaluator, which is large, so they load on first visit.
const LessonPage = lazy(() => import("./learn/LessonPage"));
// Play needs the full game engine, so it loads on first visit too.
const PlayPage = lazy(() => import("./play/PlayPage"));
const ReviewPage = lazy(() => import("./review/ReviewPage"));

const AREAS: { area: Route["area"]; label: MessageId }[] = [
  { area: "learn", label: "app.learn" },
  { area: "play", label: "app.play" },
  { area: "review", label: "app.review" },
];

// One loading screen for everything: a page's language, its code, and its lesson text all wait here. On the first load
// it stays up until all of them are ready; after that, moving to another page keeps the current one on screen until
// the next is ready (see useHash), with the loading screen over it only if that takes a while.
export default function App() {
  const [hash, navigating] = useHash();
  const { locale, route } = parseLocation(hash);
  return (
    <LanguageErrorBoundary locale={locale} englishHref={routeHref(route)}>
      <Suspense fallback={<LoadingLanguage />}>
        <I18nProvider locale={locale}>
          <Shell hash={hash} />
        </I18nProvider>
      </Suspense>
      {navigating && <LoadingLanguage later />}
    </LanguageErrorBoundary>
  );
}

const REPO = "https://github.com/Cherish-Chen9336/poker-tutor";
// Creative Commons' summary of the license, in the page's language.
const DEED: Record<Locale, string> = { en: "en", "zh-Hans": "zh-hans", ja: "ja" };

function Shell({ hash }: { hash: string }) {
  const { route } = parseLocation(hash);
  const t = useT();
  const locale = useLocale();
  const [privacyOpen, setPrivacyOpen] = useState(false);
  const href = useHref();
  const page =
    route.area === "learn"
      ? route.lesson !== null && findLesson(route.lesson)
        ? t(`lesson.${route.lesson}.title` as MessageId)
        : t("app.learn")
      : t(route.area === "play" ? "app.play" : "app.review");
  const title = t("app.title", { page });
  const { progress, saved, complete, reset } = useProgress();
  const main = useRef<HTMLElement>(null);
  const firstRender = useRef(true);

  // After moving to another page, start at the top and move keyboard and
  // screen-reader focus to the new page's heading.
  useEffect(() => {
    document.title = title;
    if (firstRender.current) {
      firstRender.current = false;
      return;
    }
    window.scrollTo(0, 0);
    focusPageHeading(main.current);
  }, [hash, title]);

  return (
    <div className="shell">
      <header className="top">
        <a className="brand" href={href({ area: "learn", lesson: null })}>
          {t("app.brand")}
        </a>
        <nav className="tabs" aria-label={t("app.areas")}>
          {AREAS.map(({ area, label }) => (
            <a
              key={area}
              href={href(area === "learn" ? { area, lesson: null } : { area })}
              aria-current={route.area === area ? "page" : undefined}
            >
              {t(label)}
            </a>
          ))}
        </nav>
      </header>
      <div className="lang-bar">
        <LanguageSwitch route={route} />
        <MachineLabel />
      </div>

      <main ref={main}>
        {route.area === "learn" && route.lesson === null && (
          <LearnHome progress={progress} saved={saved} onReset={reset} />
        )}
        {route.area === "learn" && route.lesson !== null && (
          <LessonPage key={route.lesson} lessonId={route.lesson} progress={progress} onComplete={complete} />
        )}
        {route.area === "play" && <PlayPage />}
        {route.area === "review" && <ReviewPage />}
      </main>

      <footer className="foot">
        <span>
          {t("app.footer")} <span className="nowrap">© 2026 Cherish-Chen9336</span>
        </span>
        <span className="foot-links">
          <a href={`${REPO}/blob/main/LICENSE`}>{t("app.codeLicense")}</a>
          <a href={`https://creativecommons.org/licenses/by/4.0/deed.${DEED[locale]}`}>{t("app.contentLicense")}</a>
          {/* Generated by the build (vite.config.ts). */}
          <a href="./third-party-licenses.txt">{t("app.thirdParty")}</a>
          <a href={REPO}>{t("app.source")}</a>
          {/* The privacy details stay one tap away, so the footer itself is a single line. */}
          <button type="button" className="foot-toggle" aria-expanded={privacyOpen} aria-controls="privacy" onClick={() => setPrivacyOpen(!privacyOpen)}>
            {t("app.privacyLink")}
          </button>
        </span>
        {privacyOpen && (
          <p className="foot-note" id="privacy">
            {t("app.privacy")}
          </p>
        )}
      </footer>
    </div>
  );
}
